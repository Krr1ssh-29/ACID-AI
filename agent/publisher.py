"""GitHub repair integration and Draft Pull Request deliverer."""
import os
import re
import subprocess
import requests
from typing import Dict, Any, Optional, List, Tuple
from agent.models import (
    AgentConfig,
    PatchProposal,
    VerificationResult,
    VerificationStatus,
    PatchStatus,
    PublishResult,
    PublishStatus,
    FilePatch,
)
from agent.security import redact_secrets

RECURSION_TAG = "[ai-agent-repair]"
DEFAULT_BASE_BRANCH = "main"
MAX_DIFF_SNIPPET_CHARS = 10000
MAX_OUTPUT_SNIPPET_CHARS = 4000


def sanitize_branch_slug(name: str) -> str:
    """Sanitize arbitrary string into a safe Git branch slug.

    Args:
        name: Raw identifier or category string.

    Returns:
        Alphanumeric slug with hyphens, lowercase, max 30 chars.
    """
    if not name:
        return "repair"
    cleaned = re.sub(r"[^a-zA-Z0-9_-]", "-", str(name)).strip("-").lower()
    cleaned = re.sub(r"-+", "-", cleaned)
    return cleaned[:30] if cleaned else "repair"


def is_recursive_trigger(config: AgentConfig, repo_root: Optional[str] = None) -> bool:
    """Check whether the active workflow run was triggered recursively.

    Checks:
    1. Actor identity: detects github-actions[bot] or bot actors.
    2. Commit message: checks for [ai-agent-repair] anti-recursion tag.

    Args:
        config: Current AgentConfig.
        repo_root: Optional path to repository root.

    Returns:
        True if triggered by a bot or repair commit, False otherwise.
    """
    actor = config.github_actor or os.environ.get("GITHUB_ACTOR", "")
    if actor and (actor == "github-actions[bot]" or actor.endswith("[bot]")):
        return True

    # Check commit message via local git if repository root is provided
    if repo_root and os.path.isdir(os.path.join(repo_root, ".git")):
        commit_sha = config.commit_sha
        if commit_sha and commit_sha != "unknown":
            try:
                cmd = ["git", "show", "-s", "--format=%B", commit_sha]
                result = subprocess.run(
                    cmd,
                    cwd=repo_root,
                    capture_output=True,
                    text=True,
                    timeout=5,
                )
                if result.returncode == 0 and RECURSION_TAG in result.stdout:
                    return True
            except Exception:
                pass

    return False


def format_repair_pr_title(category: str, run_id: str) -> str:
    """Format standardized Draft PR title with anti-recursion tag."""
    return f"{RECURSION_TAG} Fix {category} failure in run #{run_id}"


def format_repair_pr_body(
    diagnosis: Dict[str, Any],
    patch: PatchProposal,
    verification: VerificationResult,
    config: AgentConfig,
    target_branch: Optional[str] = None,
) -> str:
    """Construct clear, comprehensive Draft PR markdown description.

    Contains:
    - Diagnosed failure (summary, categories, root cause, run link).
    - Proposed fix (explanation, files modified, unified diff).
    - Actual verification evidence (sandbox status, exit code, commands, console output).
    - Explicit truthfulness disclaimer and human review requirement.

    Args:
        diagnosis: AI diagnostic summary dictionary.
        patch: Validated PatchProposal.
        verification: Actual VerificationResult.
        config: AgentConfig.
        target_branch: Optional target branch for the draft PR.

    Returns:
        Markdown string for Draft PR body.
    """
    raw_cats = diagnosis.get("failure_types", ["unknown"])
    if isinstance(raw_cats, str):
        cats_list = [c.strip() for c in raw_cats.split(",") if c.strip()]
    else:
        cats_list = list(raw_cats)
    categories_badges = " ".join([f"`{c}`" for c in cats_list])

    run_url = f"https://github.com/{config.repo_name}/actions/runs/{config.run_id}"
    root_cause = diagnosis.get("root_cause", "No detailed root cause provided.")
    if config.pr_number:
        head_info = f" (head: `{config.head_ref}`)" if config.head_ref else ""
        trigger_context_line = f"- **Trigger Context:** Pull Request `#{config.pr_number}`{head_info}"
    else:
        pushed_branch = target_branch or config.ref_name or config.base_branch or DEFAULT_BASE_BRANCH
        trigger_context_line = f"- **Trigger Context:** Direct Push (`{pushed_branch}`)"

    files_list_md = "\n".join([f"- `{fp.path}` ({fp.status}, +{fp.additions}/-{fp.deletions})" for fp in patch.files])

    diff_snippet = patch.diff[:MAX_DIFF_SNIPPET_CHARS]
    if len(patch.diff) > MAX_DIFF_SNIPPET_CHARS:
        diff_snippet += "\n... [diff truncated for length] ..."

    cmds_md = "\n".join([f"- `{cmd}`" for cmd in verification.executed_commands]) or "- `(none recorded)`"

    output_snippet = (verification.output or "No console output recorded.")[-MAX_OUTPUT_SNIPPET_CHARS:]

    body = f"""## 🤖 ACID AI — Automated Repair Proposal {RECURSION_TAG}

> [!NOTE]
> **Draft Pull Request Notice:** This pull request was automatically generated by
> ACID AI and opened as a **Draft**.
> Automated repairs are never merged automatically. Human review and approval are **mandatory** before merging.

---

### 🔍 Diagnosed Pipeline Failure
- **Workflow Run ID:** [{config.run_id}]({run_url})
- **Failed Commit SHA:** `{config.commit_sha}`
{trigger_context_line}
- **Failure Categories:** {categories_badges}
- **Root Cause Analysis:**
> {root_cause}

---

### 🛠️ Proposed Solution & Code Patch
- **Patch Explanation:** {patch.explanation}
- **Files Modified ({len(patch.files)}):**
{files_list_md}

<details>
<summary>📄 Unified Diff</summary>

```diff
{diff_snippet}
```

</details>

---

### 🧪 Isolated Sandbox Verification Evidence
- **Verification Status:** `{verification.status.value.upper()}`
- **Test Exit Code:** `{verification.exit_code}`
- **Verification Commands Executed:**
{cmds_md}

<details open>
<summary>🔬 Verification Console Output</summary>

```
{output_snippet}
```

</details>

---

### 🛡️ Truthfulness & Verification Disclaimer
> [!IMPORTANT]
> **Passing verification proves ONLY that the executed test suite returned exit code 0 inside the isolated sandbox.**
> It does **NOT** prove that the patch is bug-free, performant, or free of edge-case regressions not covered
> by the existing test suite. Human engineering review remains strictly required.

{RECURSION_TAG}
"""
    return redact_secrets(body)


def _extract_diff_hunks(diff_content: str) -> List[Tuple[int, int, List[str]]]:
    """Parse hunk headers and hunk content lines from unified diff text."""
    hunk_regex = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")
    hunks: List[Tuple[int, int, List[str]]] = []
    current_lines: List[str] = []
    orig_start = 0
    orig_count = 1

    for line in diff_content.splitlines():
        match = hunk_regex.match(line)
        if match:
            if current_lines:
                hunks.append((orig_start, orig_count, current_lines))
                current_lines = []
            orig_start = int(match.group(1))
            orig_count = int(match.group(2)) if match.group(2) else 1
            continue
        if orig_start > 0:
            current_lines.append(line)

    if current_lines:
        hunks.append((orig_start, orig_count, current_lines))

    return hunks


def get_patched_file_content(
    file_patch: FilePatch,
    repo_root: Optional[str] = None,
    base_branch: str = "main",
    repo_name: Optional[str] = None,
    headers: Optional[Dict[str, str]] = None,
) -> str:
    """Derive modified file content in-memory without modifying host repository.

    Args:
        file_patch: Target FilePatch.
        repo_root: Optional local repository root.
        base_branch: Target base branch name.
        repo_name: GitHub repository in owner/repo format.
        headers: Optional GitHub API request headers.

    Returns:
        New content string for the file.
    """
    if file_patch.status == "added":
        added_lines = []
        for line in file_patch.diff_content.splitlines():
            if line.startswith("+") and not line.startswith("+++"):
                added_lines.append(line[1:])
        return "\n".join(added_lines) + ("\n" if added_lines else "")

    # For modified files, read base content
    orig_content = ""
    if repo_root:
        local_path = os.path.join(repo_root, file_patch.path)
        if os.path.isfile(local_path):
            try:
                with open(local_path, "r", encoding="utf-8", errors="replace") as f:
                    orig_content = f.read()
            except OSError:
                orig_content = ""

    if not orig_content and repo_name and headers:
        # Fallback: Fetch file from GitHub API
        url = f"https://api.github.com/repos/{repo_name}/contents/{file_patch.path}?ref={base_branch}"
        try:
            resp = requests.get(url, headers=headers, timeout=20)
            if resp.status_code == 200:
                raw_b64 = resp.json().get("content", "")
                encoding = resp.json().get("encoding", "")
                if encoding == "base64":
                    import base64
                    orig_content = base64.b64decode(raw_b64).decode("utf-8", errors="replace")
                else:
                    orig_content = raw_b64
        except Exception:
            pass

    # Apply hunks to lines
    lines = orig_content.splitlines()
    hunks = _extract_diff_hunks(file_patch.diff_content)
    modified_lines = list(lines)

    for orig_start, _, hunk_lines in hunks:
        expected_orig = [hl[1:] for hl in hunk_lines if hl.startswith((" ", "-"))]
        replacement = [hl[1:] for hl in hunk_lines if hl.startswith((" ", "+"))]
        start_idx = max(0, orig_start - 1)

        matched_idx = None
        for offset in range(max(10, len(modified_lines))):
            for candidate in (start_idx + offset, start_idx - offset):
                if 0 <= candidate <= len(modified_lines) - len(expected_orig):
                    if modified_lines[candidate : candidate + len(expected_orig)] == expected_orig:
                        matched_idx = candidate
                        break
            if matched_idx is not None:
                break

        if matched_idx is None:
            raise ValueError(
                f"Patch hunk starting at line {orig_start} did not match base content for '{file_patch.path}'."
            )

        modified_lines[matched_idx : matched_idx + len(expected_orig)] = replacement

    return "\n".join(modified_lines) + ("\n" if modified_lines else "")


def check_existing_pr(
    repo_name: str,
    branch_name: str,
    headers: Dict[str, str],
) -> Optional[Dict[str, Any]]:
    """Query GitHub API to check if an open pull request already exists for branch.

    Args:
        repo_name: Repository in owner/repo format.
        branch_name: Branch name to check.
        headers: Authenticated request headers.

    Returns:
        Pull request data dictionary if found, None otherwise.
    """
    owner = repo_name.split("/")[0] if "/" in repo_name else ""
    url = f"https://api.github.com/repos/{repo_name}/pulls"
    params = {"head": f"{owner}:{branch_name}", "state": "open"}
    try:
        resp = requests.get(url, headers=headers, params=params, timeout=20)
        if resp.status_code == 200:
            prs = resp.json()
            if isinstance(prs, list) and len(prs) > 0:
                return prs[0]
    except requests.RequestException:
        pass
    return None


def handle_fork_fallback(
    patch: PatchProposal,
    config: AgentConfig,
    reason: str,
    verification: Optional[VerificationResult] = None,
) -> None:
    """Execute graceful fallback when PR/branch creation is blocked by fork or permissions.

    1. Writes patch unified diff to 'agent-patch.diff' for workflow artifact capture.
    2. If running in a PR context, posts diagnostic comment containing diff.
    3. Truthfully reports verification status: never claims sandbox verification unless
       actual status is VERIFIED_SUCCESS with exit code 0, and includes the T-13 disclaimer.

    Args:
        patch: Candidate PatchProposal.
        config: Current AgentConfig.
        reason: Explanation of the permission or fork limitation.
        verification: Optional VerificationResult to verify actual status.
    """
    # 1. Save artifact file
    try:
        with open("agent-patch.diff", "w", encoding="utf-8") as f:
            f.write(redact_secrets(patch.diff))
        print("💾 Fallback: Saved patch diff to 'agent-patch.diff' for artifact upload.")
    except Exception as e:
        print(f"⚠️ Could not write 'agent-patch.diff': {e}")

    # 2. Post PR comment if target PR number is present
    token = config.publisher_token or config.github_token
    if config.pr_number and token:
        is_verified_success = (
            verification is not None
            and verification.is_verified is True
            and verification.exit_code == 0
            and verification.status in (VerificationStatus.VERIFIED, VerificationStatus.VERIFIED_SUCCESS)
        )

        if is_verified_success:
            verif_notice = (
                "The candidate fix has been verified in an isolated sandbox with exit code 0.\n\n"
                "> [!IMPORTANT]\n"
                "> **Truthful verification notice:** Passing verification proves ONLY that the executed "
                "test suite returned exit code 0 inside the isolated sandbox. It does NOT prove that the "
                "patch is bug-free, performant, or free of edge-case regressions. "
                "Human engineering review remains strictly required."
            )
        else:
            verif_notice = (
                "⚠️ **UNVERIFIED CANDIDATE FIX:** This patch has **NOT** passed isolated sandbox verification. "
                "Passing tests or bug-free fixes are neither claimed nor guaranteed."
            )

        fallback_body = (
            f"## 🤖 ACID AI — Patch Proposal {RECURSION_TAG}\n\n"
            f"⚠️ **Notice:** Automated repair branch creation was blocked due to repository write permissions "
            f"or fork limitations (`{reason}`).\n\n"
            f"{verif_notice}\n\n"
            f"You can review and apply this patch manually:\n\n"
            f"```diff\n{patch.diff[:MAX_DIFF_SNIPPET_CHARS]}\n```\n\n"
            f"{RECURSION_TAG}"
        )
        try:
            from agent.github import post_pr_comment
            clean_body = redact_secrets(fallback_body)
            post_pr_comment(clean_body, config.repo_name, config.pr_number, token)
        except Exception as e:
            print(f"⚠️ Could not post fallback PR comment: {e}")
    else:
        print(
            "ℹ️ Direct push run (no PR context): skipped PR comment. "
            "Patch diff preserved in 'agent-patch.diff' artifact."
        )


def publish_repair_pr(
    patch: PatchProposal,
    verification: VerificationResult,
    diagnosis: Dict[str, Any],
    config: AgentConfig,
    repo_root: Optional[str] = None,
) -> PublishResult:
    """Publish a verified code repair as a dedicated Git branch and Draft Pull Request.

    Adheres strictly to all security, anti-recursion, and truthfulness policies:
    1. NEVER creates a repair PR representing a patch as verified unless actual
       verification status is VERIFIED_SUCCESS (exit code 0, is_verified True).
    2. Aborts immediately if workflow run was triggered recursively by a bot or repair commit.
    3. Guarantees draft: True; auto-merging is permanently prohibited.
    4. Handles fork limitations and permission errors gracefully without crashing.
    5. Preserves host repository immutability; never modifies local working tree.

    Args:
        patch: Validated candidate PatchProposal.
        verification: Outcome from isolated sandbox execution.
        diagnosis: AI diagnosis context dictionary.
        config: Agent configuration.
        repo_root: Optional local repository root path.

    Returns:
        Structured PublishResult model.
    """
    # 1. Check if repair PR publishing is enabled
    if not config.enable_repair_pr:
        return PublishResult(
            status=PublishStatus.SKIPPED_UNVERIFIED,
            message="Repair PR publishing is disabled in configuration (ENABLE_REPAIR_PR=false).",
        )

    # 2. Anti-recursion safeguard
    if is_recursive_trigger(config, repo_root):
        return PublishResult(
            status=PublishStatus.SKIPPED_RECURSION,
            message=(
                f"Aborting repair PR creation: workflow was triggered by bot actor '{config.github_actor}' "
                f"or repair commit '{config.commit_sha[:8]}'."
            ),
        )

    # 3. CRITICAL VERIFICATION POLICY GATE
    # Never create a repair PR representing a patch as verified unless actual verification
    # status is VERIFIED_SUCCESS. In environments where disk quotas are unenforced, candidate
    # execution is blocked and returns INFRASTRUCTURE_FAILURE.
    is_verified_success = (
        verification.is_verified is True
        and verification.exit_code == 0
        and verification.status in (VerificationStatus.VERIFIED, VerificationStatus.VERIFIED_SUCCESS)
    )

    if not is_verified_success:
        return PublishResult(
            status=PublishStatus.SKIPPED_UNVERIFIED,
            message=(
                f"Refusing to publish repair PR: candidate code verification failed or was blocked "
                f"(status='{verification.status.value}', is_verified={verification.is_verified}, "
                f"exit_code={verification.exit_code}). "
                f"Repairs are published exclusively when verified in an isolated sandbox with exit code 0."
            ),
        )

    # 4. Patch policy validation
    if patch.status != PatchStatus.VALIDATED or not patch.validation or not patch.validation.is_valid:
        return PublishResult(
            status=PublishStatus.SKIPPED_UNVERIFIED,
            message="Refusing to publish repair PR: patch failed safety policy validation.",
        )

    if not patch.files:
        return PublishResult(
            status=PublishStatus.SKIPPED_UNVERIFIED,
            message="Refusing to publish repair PR: patch contains no modified files.",
        )

    # 5. Check credentials
    token = config.publisher_token or config.github_token
    if not token or not config.repo_name:
        return PublishResult(
            status=PublishStatus.PERMISSION_ERROR,
            message="Cannot publish repair PR: GITHUB_TOKEN or REPAIR_PUBLISHER_TOKEN, and REPO_NAME are missing.",
        )

    if "/" not in config.repo_name:
        return PublishResult(
            status=PublishStatus.PERMISSION_ERROR,
            message=f"Cannot publish repair PR: Repository '{config.repo_name}' is not in valid owner/repo format.",
        )

    repo = config.repo_name
    headers = {
        "Authorization": f"token {token}",
        "Accept": "application/vnd.github+json",
        "User-Agent": "ACID-AI",
    }

    is_pr = bool(
        (config.pr_number and str(config.pr_number).strip() not in ("", "None", "null"))
        or config.event_name == "pull_request"
    )

    # External Fork Detection:
    # If the pull request originates from an external fork repository, write access to the source
    # repository is unavailable and attempting branch creation on the base repository targeting
    # an external branch is invalid. Per ROADMAP.md, ACID AI never attempts unauthorized writes;
    # it safely triggers the artifact and PR comment fallback.
    if is_pr and config.pr_head_repo:
        head_repo_clean = config.pr_head_repo.strip().lower()
        base_repo_clean = repo.strip().lower()
        if head_repo_clean != base_repo_clean:
            handle_fork_fallback(
                patch,
                config,
                f"External fork PR: source repository '{config.pr_head_repo}' differs from base repository '{repo}'",
                verification=verification,
            )
            return PublishResult(
                status=PublishStatus.FORK_LIMITATION,
                message=(
                    f"External fork PR detected: source repository '{config.pr_head_repo}' differs from "
                    f"base repository '{repo}'. Aborting direct branch creation to prevent unauthorized "
                    "write attempts. Saved patch to 'agent-patch.diff' and posted PR diagnostic comment."
                ),
            )

    # Branch Targeting & Source Commit Identification:
    # 1. Same-repository PR failure: Target PR head branch (config.head_ref) with the draft PR,
    #    and base the repair branch on the PR head commit (config.pr_head_sha).
    #    Never confuse github.base_ref (the PR's target branch) with github.head_ref (the source branch).
    # 2. Direct push failure: Target the pushed branch (config.ref_name or config.base_branch).
    if is_pr:
        target_branch = config.head_ref or config.base_branch or DEFAULT_BASE_BRANCH
    else:
        target_branch = config.ref_name or config.base_branch or DEFAULT_BASE_BRANCH

    # 6. Construct dedicated repair branch name
    raw_cats = diagnosis.get("failure_types", ["repair"])
    primary_cat = raw_cats[0] if isinstance(raw_cats, list) and raw_cats else str(raw_cats)
    cat_slug = sanitize_branch_slug(primary_cat)
    run_slug = sanitize_branch_slug(config.run_id)
    branch_name = f"agent/fix-{cat_slug}-{run_slug}"

    # 7. Check idempotency: does the branch or PR already exist?
    try:
        ref_check_url = f"https://api.github.com/repos/{repo}/git/ref/heads/{branch_name}"
        ref_resp = requests.get(ref_check_url, headers=headers, timeout=20)
        if ref_resp.status_code == 401:
            return PublishResult(
                status=PublishStatus.PERMISSION_ERROR,
                branch_name=branch_name,
                message=f"401 Unauthorized: Invalid or expired GITHUB_TOKEN for repository '{repo}'.",
            )
        if ref_resp.status_code == 200:
            existing_pr = check_existing_pr(repo, branch_name, headers)
            if existing_pr:
                return PublishResult(
                    status=PublishStatus.SKIPPED_ALREADY_EXISTS,
                    branch_name=branch_name,
                    pr_number=existing_pr.get("number"),
                    pr_url=existing_pr.get("html_url"),
                    message=f"Repair PR #{existing_pr.get('number')} already exists for run '{config.run_id}'.",
                )

            # Partial publication recovery: branch exists from prior run, but PR creation failed.
            existing_branch_sha = ref_resp.json().get("object", {}).get("sha", "")
            commit_check_url = f"https://api.github.com/repos/{repo}/git/commits/{existing_branch_sha}"
            commit_resp = requests.get(commit_check_url, headers=headers, timeout=20)
            if commit_resp.status_code != 200:
                return PublishResult(
                    status=PublishStatus.API_ERROR,
                    branch_name=branch_name,
                    message=(
                        f"Existing repair branch '{branch_name}' found, but failed to inspect its commit: "
                        f"HTTP {commit_resp.status_code}"
                    ),
                )
            commit_data = commit_resp.json()
            commit_msg = commit_data.get("message", "")

            # Safety validation: Verify commit belongs to this automated repair and run ID
            if RECURSION_TAG not in commit_msg or config.run_id not in commit_msg:
                return PublishResult(
                    status=PublishStatus.API_ERROR,
                    branch_name=branch_name,
                    commit_sha=existing_branch_sha,
                    message=(
                        f"Existing branch '{branch_name}' commit ({existing_branch_sha[:8]}) does not match "
                        f"expected repair metadata for run '{config.run_id}'. "
                        "Refusing to create PR on unvalidated branch."
                    ),
                )

            # Validated existing branch: retry Draft PR creation
            pr_title = format_repair_pr_title(cat_slug, config.run_id)
            pr_body = format_repair_pr_body(diagnosis, patch, verification, config, target_branch=target_branch)
            pr_payload = {
                "title": pr_title,
                "body": pr_body,
                "head": branch_name,
                "base": target_branch,
                "draft": True,
            }
            pulls_url = f"https://api.github.com/repos/{repo}/pulls"
            pulls_resp = requests.post(pulls_url, headers=headers, json=pr_payload, timeout=30)
            if pulls_resp.status_code == 201:
                pr_data = pulls_resp.json()
                return PublishResult(
                    status=PublishStatus.PUBLISHED,
                    branch_name=branch_name,
                    pr_number=pr_data.get("number"),
                    pr_url=pr_data.get("html_url"),
                    commit_sha=existing_branch_sha,
                    is_draft=True,
                    message=f"Recovered from partial publication: created Draft PR #{pr_data.get('number')}.",
                )
            elif pulls_resp.status_code == 403:
                handle_fork_fallback(
                    patch, config, "403 Forbidden creating PR during recovery", verification=verification
                )
                return PublishResult(
                    status=PublishStatus.FORK_LIMITATION,
                    branch_name=branch_name,
                    commit_sha=existing_branch_sha,
                    message=(
                        "403 Forbidden creating Draft PR during recovery: "
                        "fork limitation or missing pull-requests:write scope."
                    ),
                )
            elif pulls_resp.status_code == 422:
                concurrent_pr = check_existing_pr(repo, branch_name, headers)
                if concurrent_pr:
                    return PublishResult(
                        status=PublishStatus.SKIPPED_ALREADY_EXISTS,
                        branch_name=branch_name,
                        pr_number=concurrent_pr.get("number"),
                        pr_url=concurrent_pr.get("html_url"),
                        commit_sha=existing_branch_sha,
                        message=f"Draft Pull Request #{concurrent_pr.get('number')} already exists.",
                    )
                return PublishResult(
                    status=PublishStatus.API_ERROR,
                    branch_name=branch_name,
                    commit_sha=existing_branch_sha,
                    message=f"Pull request rejected (HTTP 422) during recovery: {pulls_resp.text}",
                )
            else:
                return PublishResult(
                    status=PublishStatus.API_ERROR,
                    branch_name=branch_name,
                    commit_sha=existing_branch_sha,
                    message=f"Pull request creation failed during recovery: HTTP {pulls_resp.status_code}",
                )
        elif ref_resp.status_code == 403:
            handle_fork_fallback(
                patch, config, "403 Forbidden checking branch existence", verification=verification
            )
            return PublishResult(
                status=PublishStatus.FORK_LIMITATION,
                branch_name=branch_name,
                message=f"403 Forbidden on repository '{repo}' (fork limitation or insufficient token permissions).",
            )
    except requests.RequestException as e:
        return PublishResult(
            status=PublishStatus.API_ERROR,
            message=f"Network error querying GitHub API: {e}",
        )

    # 8. Fetch target branch commit SHA
    try:
        base_ref_url = f"https://api.github.com/repos/{repo}/git/ref/heads/{target_branch}"
        base_resp = requests.get(base_ref_url, headers=headers, timeout=20)
        if base_resp.status_code == 200:
            branch_tip_sha = base_resp.json()["object"]["sha"]
        elif base_resp.status_code == 401:
            return PublishResult(
                status=PublishStatus.PERMISSION_ERROR,
                message=f"401 Unauthorized: Invalid or expired GITHUB_TOKEN for repository '{repo}'.",
            )
        elif base_resp.status_code == 404:
            # Fallback to branches endpoint
            b_url = f"https://api.github.com/repos/{repo}/branches/{target_branch}"
            b_resp = requests.get(b_url, headers=headers, timeout=20)
            if b_resp.status_code == 200:
                branch_tip_sha = b_resp.json()["commit"]["sha"]
            elif b_resp.status_code == 401:
                return PublishResult(
                    status=PublishStatus.PERMISSION_ERROR,
                    message=f"401 Unauthorized: Invalid or expired GITHUB_TOKEN for repository '{repo}'.",
                )
            else:
                return PublishResult(
                    status=PublishStatus.API_ERROR,
                    message=f"Target branch '{target_branch}' not found on repository '{repo}'.",
                )
        elif base_resp.status_code == 403:
            handle_fork_fallback(
                patch, config, f"403 Forbidden accessing target branch '{target_branch}'", verification=verification
            )
            return PublishResult(
                status=PublishStatus.FORK_LIMITATION,
                message=f"403 Forbidden reading target branch '{target_branch}' on '{repo}'.",
            )
        else:
            return PublishResult(
                status=PublishStatus.API_ERROR,
                message=f"Failed to fetch target branch '{target_branch}': HTTP {base_resp.status_code}",
            )
    except requests.RequestException as e:
        return PublishResult(
            status=PublishStatus.API_ERROR,
            message=f"Network error fetching target branch commit: {e}",
        )

    # Exact base SHA resolution:
    # On same-repository PR runs, the repair branch must be based on the PR head commit (pr_head_sha).
    # On push runs or when pr_head_sha is omitted, use the verified target branch tip SHA.
    if is_pr and config.pr_head_sha and config.pr_head_sha != "unknown":
        base_sha = config.pr_head_sha
    else:
        base_sha = branch_tip_sha

    # 9. Get base tree SHA
    try:
        commit_url = f"https://api.github.com/repos/{repo}/git/commits/{base_sha}"
        commit_resp = requests.get(commit_url, headers=headers, timeout=20)
        if commit_resp.status_code != 200:
            return PublishResult(
                status=PublishStatus.API_ERROR,
                message=f"Failed to fetch base commit tree: HTTP {commit_resp.status_code}",
            )
        base_tree_sha = commit_resp.json()["tree"]["sha"]
    except requests.RequestException as e:
        return PublishResult(
            status=PublishStatus.API_ERROR,
            message=f"Network error fetching commit tree: {e}",
        )

    # 10. Build git tree with patched file contents
    tree_items = []
    for fp in patch.files:
        try:
            content = get_patched_file_content(fp, repo_root, target_branch, repo, headers)
        except ValueError as e:
            return PublishResult(
                status=PublishStatus.API_ERROR,
                branch_name=branch_name,
                message=f"Tree generation aborted due to unmatched patch hunk: {e}",
            )
        tree_items.append({
            "path": fp.path,
            "mode": "100644",
            "type": "blob",
            "content": content,
        })

    try:
        tree_url = f"https://api.github.com/repos/{repo}/git/trees"
        tree_payload = {"base_tree": base_tree_sha, "tree": tree_items}
        tree_resp = requests.post(tree_url, headers=headers, json=tree_payload, timeout=30)
        if tree_resp.status_code == 401:
            return PublishResult(
                status=PublishStatus.PERMISSION_ERROR,
                branch_name=branch_name,
                message="401 Unauthorized creating git tree: invalid or expired GITHUB_TOKEN.",
            )
        if tree_resp.status_code == 403:
            handle_fork_fallback(patch, config, "403 Forbidden creating git tree", verification=verification)
            return PublishResult(
                status=PublishStatus.FORK_LIMITATION,
                branch_name=branch_name,
                message="403 Forbidden creating git tree: fork limitation or missing contents:write scope.",
            )
        if tree_resp.status_code != 201:
            return PublishResult(
                status=PublishStatus.API_ERROR,
                message=f"Git tree creation failed: HTTP {tree_resp.status_code} — {tree_resp.text}",
            )
        new_tree_sha = tree_resp.json()["sha"]
    except requests.RequestException as e:
        return PublishResult(
            status=PublishStatus.API_ERROR,
            message=f"Network error creating git tree: {e}",
        )

    # 11. Create commit with anti-recursion tag
    commit_msg = (
        f"fix: resolve {cat_slug} CI/CD failure {RECURSION_TAG}\n\n"
        f"Automated candidate repair for workflow run {config.run_id}.\n"
        f"Diagnosed root cause: {diagnosis.get('root_cause', 'CI/CD failure')}\n"
        f"{RECURSION_TAG}"
    )
    try:
        create_commit_url = f"https://api.github.com/repos/{repo}/git/commits"
        create_commit_payload = {
            "message": commit_msg,
            "tree": new_tree_sha,
            "parents": [base_sha],
        }
        create_commit_resp = requests.post(create_commit_url, headers=headers, json=create_commit_payload, timeout=30)
        if create_commit_resp.status_code == 401:
            return PublishResult(
                status=PublishStatus.PERMISSION_ERROR,
                branch_name=branch_name,
                message="401 Unauthorized creating git commit: invalid or expired GITHUB_TOKEN.",
            )
        if create_commit_resp.status_code == 403:
            handle_fork_fallback(patch, config, "403 Forbidden creating git commit", verification=verification)
            return PublishResult(
                status=PublishStatus.FORK_LIMITATION,
                branch_name=branch_name,
                message="403 Forbidden creating git commit.",
            )
        if create_commit_resp.status_code != 201:
            return PublishResult(
                status=PublishStatus.API_ERROR,
                message=f"Commit creation failed: HTTP {create_commit_resp.status_code} — {create_commit_resp.text}",
            )
        new_commit_sha = create_commit_resp.json()["sha"]
    except requests.RequestException as e:
        return PublishResult(
            status=PublishStatus.API_ERROR,
            message=f"Network error creating git commit: {e}",
        )

    # 12. Create branch ref (refs/heads/agent/fix-...)
    try:
        create_ref_url = f"https://api.github.com/repos/{repo}/git/refs"
        ref_payload = {"ref": f"refs/heads/{branch_name}", "sha": new_commit_sha}
        create_ref_resp = requests.post(create_ref_url, headers=headers, json=ref_payload, timeout=30)
        if create_ref_resp.status_code == 401:
            return PublishResult(
                status=PublishStatus.PERMISSION_ERROR,
                branch_name=branch_name,
                commit_sha=new_commit_sha,
                message="401 Unauthorized creating git branch: invalid or expired GITHUB_TOKEN.",
            )
        if create_ref_resp.status_code == 403:
            handle_fork_fallback(patch, config, "403 Forbidden creating git branch", verification=verification)
            return PublishResult(
                status=PublishStatus.FORK_LIMITATION,
                branch_name=branch_name,
                commit_sha=new_commit_sha,
                message="403 Forbidden creating branch: fork limitation or missing contents:write scope.",
            )
        if create_ref_resp.status_code == 422:
            return PublishResult(
                status=PublishStatus.SKIPPED_ALREADY_EXISTS,
                branch_name=branch_name,
                commit_sha=new_commit_sha,
                message=f"Branch ref 'refs/heads/{branch_name}' already exists on remote.",
            )
        if create_ref_resp.status_code != 201:
            return PublishResult(
                status=PublishStatus.API_ERROR,
                message=f"Branch ref creation failed: HTTP {create_ref_resp.status_code} — {create_ref_resp.text}",
            )
    except requests.RequestException as e:
        return PublishResult(
            status=PublishStatus.API_ERROR,
            message=f"Network error creating branch ref: {e}",
        )

    # 13. Create reviewable Draft Pull Request
    pr_title = format_repair_pr_title(cat_slug, config.run_id)
    pr_body = format_repair_pr_body(diagnosis, patch, verification, config, target_branch=target_branch)
    pr_payload = {
        "title": pr_title,
        "body": pr_body,
        "head": branch_name,
        "base": target_branch,
        "draft": True,
    }

    try:
        pulls_url = f"https://api.github.com/repos/{repo}/pulls"
        pulls_resp = requests.post(pulls_url, headers=headers, json=pr_payload, timeout=30)
        if pulls_resp.status_code == 401:
            return PublishResult(
                status=PublishStatus.PERMISSION_ERROR,
                branch_name=branch_name,
                commit_sha=new_commit_sha,
                message="401 Unauthorized creating pull request: invalid or expired GITHUB_TOKEN.",
            )
        if pulls_resp.status_code == 201:
            pr_data = pulls_resp.json()
            return PublishResult(
                status=PublishStatus.PUBLISHED,
                branch_name=branch_name,
                pr_number=pr_data.get("number"),
                pr_url=pr_data.get("html_url"),
                commit_sha=new_commit_sha,
                is_draft=True,
                message=f"Successfully published Draft Pull Request #{pr_data.get('number')}.",
            )
        elif pulls_resp.status_code == 403:
            handle_fork_fallback(patch, config, "403 Forbidden creating pull request", verification=verification)
            return PublishResult(
                status=PublishStatus.FORK_LIMITATION,
                branch_name=branch_name,
                commit_sha=new_commit_sha,
                message="403 Forbidden creating Pull Request: fork limitation or missing pull-requests:write scope.",
            )
        elif pulls_resp.status_code == 422:
            # Check if PR already exists for this branch
            existing = check_existing_pr(repo, branch_name, headers)
            if existing:
                return PublishResult(
                    status=PublishStatus.SKIPPED_ALREADY_EXISTS,
                    branch_name=branch_name,
                    pr_number=existing.get("number"),
                    pr_url=existing.get("html_url"),
                    commit_sha=new_commit_sha,
                    message=f"Draft Pull Request #{existing.get('number')} already exists.",
                )
            return PublishResult(
                status=PublishStatus.API_ERROR,
                branch_name=branch_name,
                commit_sha=new_commit_sha,
                message=f"Pull request rejected (HTTP 422): {pulls_resp.text}",
            )
        else:
            return PublishResult(
                status=PublishStatus.API_ERROR,
                branch_name=branch_name,
                commit_sha=new_commit_sha,
                message=f"Pull request creation failed: HTTP {pulls_resp.status_code} — {pulls_resp.text}",
            )
    except requests.RequestException as e:
        return PublishResult(
            status=PublishStatus.API_ERROR,
            branch_name=branch_name,
            commit_sha=new_commit_sha,
            message=f"Network error creating pull request: {e}",
        )
