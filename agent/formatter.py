"""Pull Request comment formatting utilities."""
from typing import Dict, Any, List, Optional


def format_pr_comment(
    analysis: Dict[str, Any],
    commit_sha: str,
    run_id: str,
    repo: str,
    ai_provider: Optional[str] = None,
) -> str:
    """Format structured diagnosis and fixes into a GitHub PR markdown comment.

    Args:
        analysis: Dictionary containing severity, failure_types, root_cause, fixes, etc.
        commit_sha: Git commit hash triggering the CI workflow.
        run_id: GitHub Actions workflow run identifier.
        repo: Repository identifier in 'owner/repo' format.
        ai_provider: Active provider identifier ('claude' or 'gemini').

    Returns:
        Formatted markdown string suitable for posting as a PR comment.
    """
    import os
    provider = ai_provider or os.environ.get("AI_PROVIDER", "claude").lower()
    severity_emoji = {
        "critical": "🔴",
        "high": "🟠",
        "medium": "🟡",
        "low": "🟢",
    }.get(analysis.get("severity", "high"), "🟠")

    confidence_emoji = {
        "high": "✅",
        "medium": "⚠️",
        "low": "❓",
    }.get(analysis.get("confidence", "medium"), "⚠️")

    provider_label = "Anthropic Claude Sonnet" if provider == "claude" else "Google Gemini 2.5 Flash"
    provider_badge = "🟣" if provider == "claude" else "🔵"

    raw_failure_types = analysis.get("failure_types", ["unknown"])
    if isinstance(raw_failure_types, str):
        failure_types: List[str] = [f.strip() for f in raw_failure_types.split(",")]
    else:
        failure_types = list(raw_failure_types)

    failure_badges = " ".join([f"`{ft}`" for ft in failure_types])

    fixes_md = ""
    for i, fix in enumerate(analysis.get("fixes", []), 1):
        fixes_md += f"\n#### Fix {i}: {fix.get('title', 'Suggested Fix')}\n"
        fixes_md += f"{fix.get('description', '')}\n"
        if fix.get("code"):
            fixes_md += f"\n```bash\n{fix['code']}\n```\n"

    run_url = f"https://github.com/{repo}/actions/runs/{run_id}"
    sha_short = commit_sha[:8] if commit_sha else "unknown"
    meta_header = (
        f"> **Commit:** `{sha_short}` | "
        f"**Severity:** {severity_emoji} `{analysis.get('severity', 'unknown').upper()}` | "
        f"**Confidence:** {confidence_emoji} `{analysis.get('confidence', 'medium')}` | "
        f"**AI:** {provider_badge} `{provider_label}`"
    )

    from agent.security import redact_secrets

    comment_body = f"""## 🤖 ACID AI — Pipeline Analysis

{meta_header}

---

### 🔍 Failure Types Detected
{failure_badges}

---

### 🧠 Root Cause Analysis
{analysis.get('root_cause', 'Unable to determine root cause.')}

---

### 🛠️ Suggested Fixes
{fixes_md}

---

### 🛡️ Prevention
> {analysis.get('prevention', 'No prevention advice available.')}

---

<details>
<summary>📋 Pipeline Run Details</summary>

- **Run ID:** [{run_id}]({run_url})
- **Commit:** `{commit_sha}`
- **AI Provider:** {provider_label}
- **Configured via:** `AI_PROVIDER` environment variable

</details>

---
*🤖 Generated by [ACID AI](https://github.com/{repo}). AI-Powered CI/CD Failure Diagnosis & Self-Healing.*"""

    return redact_secrets(comment_body)
